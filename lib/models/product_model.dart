class Product {
  final int id;
  final String title;
  final String artist;
  final String year;
  final String condition;
  final double price;
  final String description;
  final String imagePath;

  Product({
    required this.id,
    required this.title,
    required this.artist,
    required this.year,
    required this.condition,
    required this.price,
    required this.description,
    required this.imagePath,
  });
}
